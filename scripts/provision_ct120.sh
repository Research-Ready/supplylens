#!/usr/bin/env bash
# UC4 Supply Chain — Provision CT129 (Kotaemon RAG UI)
#
# Creates LXC container CT129 on Proxmox node-1 (10.0.0.16),
# installs Docker, deploys Kotaemon via Docker.
#
# Usage:
#   bash scripts/provision_ct120.sh            # full provision
#   bash scripts/provision_ct120.sh --redeploy # skip pct create, redo Docker only
#
# Requirements:
#   - SSH access to root@10.0.0.16 (Proxmox node-1 / bastion)
#   - Debian 12 template available on node-1 local storage
#   - VPN active
#
# CT129 specs:
#   - Node:     node-1 (10.0.0.16)
#   - IP:       10.0.1.120/24, gw 10.0.1.1
#   - RAM:      4096 MB  (Kotaemon + LLM inference heavy)
#   - Disk:     20 GB
#   - Cores:    4
#   - Template: local:vztmpl/debian-12-standard_12.7-1_amd64.tar.zst

set -euo pipefail

PROXMOX_NODE="root@10.0.0.16"
CT_ID=120
CT_IP="10.0.1.120"
CT_GW="10.0.1.1"
CT_HOSTNAME="kotaemon"
CT_RAM=4096
CT_DISK=20
CT_CORES=4
TEMPLATE="local:vztmpl/debian-12-standard_12.7-1_amd64.tar.zst"
STORAGE="local-lvm"
BRIDGE="vmbr0"
KOTAEMON_PORT=8501
KOTAEMON_IMAGE="ghcr.io/cinnamon/kotaemon:latest"
LITELLM_URL="http://localhost:4000/v1"
QDRANT_URL="http://localhost:6333"

REDEPLOY="${1:-}"

echo "╔══════════════════════════════════════════════════╗"
echo "║  UC4 — Provisioning Kotaemon CT${CT_ID} on node-1  ║"
echo "╚══════════════════════════════════════════════════╝"
echo

# ---------------------------------------------------------------------------
# Step 1: Get secrets
# ---------------------------------------------------------------------------
LITELLM_KEY=$(ssh root@10.0.2.205 "grep master_key /etc/litellm/config.yaml | awk '{print \$2}'" 2>/dev/null || echo "")
QDRANT_KEY=$(grep qdrant_api_key ansible/inventory/group_vars/vault.yml 2>/dev/null | awk '{print $2}' | tr -d '"' || echo "")
KOTAEMON_PW=$(grep kotaemon_password ansible/inventory/group_vars/vault.yml 2>/dev/null | awk '{print $2}' | tr -d '"' || echo "kotaemon_admin_2026")

echo "LiteLLM key: ${LITELLM_KEY:0:6}..."
echo "Kotaemon admin password: ${KOTAEMON_PW:0:4}..."

# ---------------------------------------------------------------------------
# Step 2: Create LXC container (skip if --redeploy)
# ---------------------------------------------------------------------------
if [[ "$REDEPLOY" != "--redeploy" ]]; then
  echo
  echo "[1/5] Checking if CT${CT_ID} exists..."
  EXISTS=$(ssh "$PROXMOX_NODE" "pct status ${CT_ID} 2>/dev/null | head -1 || echo 'notfound'")
  if echo "$EXISTS" | grep -q "notfound"; then
    echo "  Creating CT${CT_ID}..."
    ssh "$PROXMOX_NODE" "pct create ${CT_ID} ${TEMPLATE} \
      --hostname ${CT_HOSTNAME} \
      --memory ${CT_RAM} \
      --cores ${CT_CORES} \
      --rootfs ${STORAGE}:${CT_DISK} \
      --net0 name=eth0,bridge=${BRIDGE},ip=${CT_IP}/24,gw=${CT_GW} \
      --nameserver 1.1.1.1 \
      --searchdomain research-ready.nl \
      --unprivileged 1 \
      --features nesting=1 \
      --start 1 \
      --onboot 1"
    echo "  CT${CT_ID} created and started."
    sleep 8
  else
    echo "  CT${CT_ID} already exists ($EXISTS). Starting..."
    ssh "$PROXMOX_NODE" "pct start ${CT_ID} 2>/dev/null || true"
    sleep 4
  fi
else
  echo "[1/5] Skipping CT creation (--redeploy mode)."
fi

# ---------------------------------------------------------------------------
# Step 3: Install Docker inside CT129
# ---------------------------------------------------------------------------
echo
echo "[2/5] Installing Docker in CT${CT_ID}..."
ssh "$PROXMOX_NODE" "pct exec ${CT_ID} -- bash -c '
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl gnupg lsb-release
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/debian/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=\$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] \
    https://download.docker.com/linux/debian \$(lsb_release -cs) stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin
  systemctl enable --now docker
  echo "Docker version: \$(docker --version)"
'"
echo "  Docker installed."

# ---------------------------------------------------------------------------
# Step 4: Write Kotaemon config
# ---------------------------------------------------------------------------
echo
echo "[3/5] Writing Kotaemon config..."
ssh "$PROXMOX_NODE" "pct exec ${CT_ID} -- bash -c '
  mkdir -p /var/lib/kotaemon/config
  cat > /var/lib/kotaemon/config/flowsettings.py << '"'"'PYEOF'"'"'
# UC4 Kotaemon configuration — auto-generated by provision_ct120.sh
KH_LLMS = {
    \"researcher-llm\": {
        \"spec\": {
            \"__type__\": \"kotaemon.llms.LCOpenAILLM\",
            \"openai_api_base\": \"${LITELLM_URL}\",
            \"openai_api_key\": \"${LITELLM_KEY:-sk-placeholder}\",
            \"model\": \"researcher-llm\",
            \"temperature\": 0,
        },
        \"default\": True,
    }
}
KH_EMBEDDINGS = {
    \"nomic-embed-text\": {
        \"spec\": {
            \"__type__\": \"kotaemon.embeddings.LCOpenAIEmbeddings\",
            \"openai_api_base\": \"${LITELLM_URL}\",
            \"openai_api_key\": \"${LITELLM_KEY:-sk-placeholder}\",
            \"model\": \"ollama/nomic-embed-text\",
        },
        \"default\": True,
    }
}
KH_ENABLE_AUTH = True
KH_SHARE_DATA_ACROSS_USERS = False
PYEOF
  echo Config written.
'"

# ---------------------------------------------------------------------------
# Step 5: Pull image and run Kotaemon
# ---------------------------------------------------------------------------
echo
echo "[4/5] Pulling and starting Kotaemon..."
ssh "$PROXMOX_NODE" "pct exec ${CT_ID} -- bash -c '
  docker stop kotaemon 2>/dev/null || true
  docker rm   kotaemon 2>/dev/null || true
  docker pull ${KOTAEMON_IMAGE}
  docker run -d --name kotaemon \
    --restart unless-stopped \
    -p ${KOTAEMON_PORT}:7860 \
    -v /var/lib/kotaemon:/app/ktem_app_data \
    -v /var/lib/kotaemon/config/flowsettings.py:/app/flowsettings.py:ro \
    -e GRADIO_SERVER_PORT=7860 \
    -e GRADIO_SERVER_NAME=0.0.0.0 \
    ${KOTAEMON_IMAGE}
  echo Kotaemon container started.
'"

# ---------------------------------------------------------------------------
# Step 6: Wait for readiness + verify
# ---------------------------------------------------------------------------
echo
echo "[5/5] Waiting for Kotaemon to become ready..."
for i in $(seq 1 30); do
  CODE=$(ssh "$PROXMOX_NODE" "pct exec ${CT_ID} -- curl -s -o /dev/null -w '%{http_code}' --connect-timeout 3 http://localhost:${KOTAEMON_PORT}/ 2>/dev/null || echo 000")
  if [[ "$CODE" == "200" ]]; then
    echo "  Kotaemon ready (HTTP 200) after ${i}s."
    break
  fi
  echo "  ${i}s: HTTP ${CODE} — waiting..."
  sleep 3
done

echo
echo "╔══════════════════════════════════════════════════╗"
echo "║  Kotaemon deployed!                              ║"
echo "║  Internal: http://${CT_IP}:${KOTAEMON_PORT}           ║"
echo "║  Admin:    admin@research-ready.nl               ║"
echo "║  Password: ${KOTAEMON_PW}                  ║"
echo "╠══════════════════════════════════════════════════╣"
echo "║  Next steps:                                     ║"
echo "║  1. python3 scripts/ingest_kotaemon.py           ║"
echo "║  2. Open Neo4j map → verify RAG augments agent   ║"
echo "╚══════════════════════════════════════════════════╝"
